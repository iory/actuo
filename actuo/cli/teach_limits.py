#!/usr/bin/env python3
"""Learn each joint's travel by hand-moving the robot. Commands nothing, ever.

Bring-up for a robot with no model: back-drive each joint through its usable
range while this listens, and it records the extremes actually reached. Those
become ``position_limit_deg`` in the robot config, which
``CubeMarsActuator._check_position_limit`` enforces on every command -- so the
envelope protects you before any URDF exists.

Measured, not assumed: the limits come from where the hardware actually went.

    actuo-teach-limits --config <robot>.yaml --shm-name <name> --seconds 120
    # macOS: --interface gs_usb --channel 0

Move every joint to both ends, then press Ctrl-C. A joint that was not moved is
reported as untaught and is NOT given a limit -- writing the range it happened
to sit in would silently lock it in place.
"""

from __future__ import annotations

import argparse
import math
import os
import select
import sys
import time


from actuo.drivers.actuators.cubemars import ERROR_NAMES  # noqa: E402
from actuo.drivers.buses.can_bus import StaleFeedbackError  # noqa: E402
from actuo.drivers.config import build_bus  # noqa: E402


def _enter_pressed():
    """True if the operator has pressed Enter (a line is waiting on stdin).

    Non-blocking: checks stdin without stealing the CAN poll loop's time, and
    swallows the line so it does not linger for the next joint. Cooked-mode
    line input is enough -- no raw terminal, no single-key handling.
    """
    if select.select([sys.stdin], [], [], 0)[0]:
        sys.stdin.readline()
        return True
    return False


def teach_one(bus, name, actuator, args):
    """Record ONE joint's extremes while the operator hand-moves it.

    Listens only -- nothing is ever commanded. Shows the joint's live angle and
    the min/max reached so far, and returns when Enter is pressed. The other
    joints are untouched; each gets its own turn.

    Returns
    -------
    (low_rad, high_rad) : tuple of float
        The extreme positions reached, in radians.
    """
    bus.poll(timeout=0.02)
    start = bus.last_state(actuator.id).position
    low = high = start
    print("\n[teach] === {} === move it slowly to BOTH ends, then press Enter "
          "for the next joint.".format(name))
    next_print = 0.0
    while True:
        bus.poll(timeout=0.02)
        bus.check_fresh()
        state = bus.last_state(actuator.id)
        if state.error:
            raise RuntimeError("{} faulted: {}".format(
                name, ERROR_NAMES.get(state.error, state.error)))
        low = min(low, state.position)
        high = max(high, state.position)

        if _enter_pressed():
            return low, high

        now = time.monotonic()
        if now >= next_print:
            span = math.degrees(high - low)
            print("  {}: {:8.2f} deg   min {:8.2f}  max {:8.2f}   span {:7.2f}"
                  .format(name, math.degrees(state.position),
                          math.degrees(low), math.degrees(high), span),
                  end="\r", flush=True)
            next_print = now + 0.05


def emit_config_snippet(taught, out):
    """Print the exact YAML to paste, per joint."""
    print("\n" + "=" * 68, file=out)
    print("Paste into each joint's `actuator:` block in the robot config:", file=out)
    print("=" * 68, file=out)
    for name, low, high in taught:
        print("\n  # {}: taught by hand {:.2f} .. {:.2f} deg".format(name, low, high),
              file=out)
        print("  - name: {}".format(name), file=out)
        print("    actuator:", file=out)
        print("      position_limit_deg: [{:.2f}, {:.2f}]".format(low, high), file=out)


URDF_TEMPLATE = """<?xml version="1.0"?>
<!-- GENERATED by actuo-teach-limits. DO NOT trust the geometry.

     The joint NAMES and the joint LIMITS below are real: the limits were
     measured by hand-moving this robot on {stamp}.

     Everything else is a PLACEHOLDER. The links are zero-size, the axes are all
     Z, and the origins are all zero, because this robot has no model yet and
     nothing here measured its kinematics. This file is only good for giving
     ros2_control a joint list with a safe range. Do NOT use it for RViz,
     collision checking, IK, or dynamics: it would be confidently wrong.

     Replace the geometry with the real model when you have one; keep the limits.
-->
<robot name="{robot}">

  <link name="base_link"/>
{body}
  <ros2_control name="{robot}" type="system">
    <hardware>
      <plugin>{plugin}</plugin>
      <param name="shm_name">{shm}</param>
      <param name="use_sim">false</param>
    </hardware>
{control}  </ros2_control>

</robot>
"""

JOINT_TEMPLATE = """
  <!-- placeholder link: no measured geometry -->
  <link name="{child}"/>
  <joint name="{name}" type="revolute">
    <parent link="{parent}"/>
    <child link="{child}"/>
    <origin xyz="0 0 0" rpy="0 0 0"/>   <!-- PLACEHOLDER -->
    <axis xyz="0 0 1"/>                 <!-- PLACEHOLDER -->
    <limit lower="{lower:.6f}" upper="{upper:.6f}" effort="{effort}" velocity="{velocity}"/>
  </joint>
"""

CONTROL_JOINT_TEMPLATE = """      <joint name="{name}">
        <command_interface name="position">
          <param name="min">{lower:.6f}</param>
          <param name="max">{upper:.6f}</param>
        </command_interface>
        <state_interface name="position"/>
        <state_interface name="velocity"/>
      </joint>
"""


def write_urdf(path, robot, shm, taught, effort, velocity, stamp, plugin):
    """Write the placeholder URDF.

    Parameters
    ----------
    path : str
        Output file.
    robot : str
        Robot name.
    shm : str
        Shared-memory segment name, written as the hardware's ``shm_name``.
    taught : list of (str, float, float)
        Joint name and taught limits in degrees.
    effort, velocity : str
        URDF effort and velocity limits.
    stamp : str
        When the limits were taught.
    plugin : str
        ros2_control hardware plugin name of the shared-memory component
        (``<package>/<Class>``), which lives outside this package.
    """
    body = []
    control = []
    parent = "base_link"
    for index, (name, low, high) in enumerate(taught):
        child = "{}_link".format(name)
        body.append(JOINT_TEMPLATE.format(
            name=name, parent=parent, child=child,
            lower=math.radians(low), upper=math.radians(high),
            effort=effort, velocity=velocity))
        control.append(CONTROL_JOINT_TEMPLATE.format(
            name=name, lower=math.radians(low), upper=math.radians(high)))
        parent = child

    with open(path, "w") as handle:
        handle.write(URDF_TEMPLATE.format(
            robot=robot, shm=shm, plugin=plugin, stamp=stamp,
            body="".join(body), control="".join(control)))


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Teach joint limits by hand-moving the robot (sends nothing)"
    )
    parser.add_argument("--config", required=True, help="robot bus YAML")
    parser.add_argument("--per-joint", action="store_true",
                        help="teach one joint at a time: move it, press Enter to "
                             "finish it and advance to the next. Its live angle "
                             "is shown while you move it. (Default records all "
                             "joints at once over --seconds.)")
    parser.add_argument("--seconds", type=float, default=120.0,
                        help="max time to record; Ctrl-C stops early (default "
                             "120). Ignored with --per-joint.")
    parser.add_argument("--margin-deg", type=float, default=2.0,
                        help="shrink each taught range inward by this much, so a "
                             "command never targets the hard stop (default 2)")
    parser.add_argument("--min-travel-deg", type=float, default=5.0,
                        help="a joint moving less than this counts as untaught "
                             "(default 5)")
    parser.add_argument("--urdf", default="",
                        help="also write a placeholder URDF here (geometry is "
                             "NOT real -- see the file's header)")
    parser.add_argument("--robot-name", default="actuo_robot")
    # The URDF's hardware <plugin> and shm name are read by the ROS 2 hardware
    # component that consumes the URDF, outside this package, so both come
    # from the caller.
    parser.add_argument("--shm-name", required=True,
                        help="shared-memory segment name the servicer creates, "
                             "written into the URDF's hardware params")
    parser.add_argument("--hardware-plugin", default="",
                        help="ros2_control plugin name of the shared-memory "
                             "hardware component (<package>/<Class>). "
                             "Required with --urdf")
    parser.add_argument("--urdf-effort", default="",
                        help="effort limit for the URDF, N*m. No default: this "
                             "stack has no kt, so it will not invent one")
    parser.add_argument("--urdf-velocity", default="",
                        help="velocity limit for the URDF, rad/s. No default "
                             "unless pole_pairs is configured")
    parser.add_argument("--interface", default=None)
    parser.add_argument("--channel", default=None)
    parser.add_argument("--bitrate", type=int, default=None)
    args = parser.parse_args(argv)
    if args.urdf and not args.hardware_plugin:
        parser.error("--urdf needs --hardware-plugin: the URDF names the "
                     "ros2_control hardware component, which this package "
                     "does not ship")

    overrides = {}
    if args.interface is not None:
        overrides["interface"] = args.interface
    if args.channel is not None:
        try:
            overrides["channel"] = int(args.channel)
        except ValueError:
            overrides["channel"] = args.channel
    if args.bitrate is not None:
        overrides["bitrate"] = args.bitrate

    bus, names = build_bus(args.config, transport_overrides=overrides or None)
    bus.transport.open()

    if args.per_joint and not sys.stdin.isatty():
        print("[teach] --per-joint waits for Enter and needs a real terminal; "
              "run it directly, not through a pipe or a `!` wrapper.",
              file=sys.stderr)
        bus.transport.close()
        return 2

    lows = {}
    highs = {}
    try:
        bus.read_batch(timeout=5.0)
        print("[teach] all {} motors reporting. NOTHING will be commanded.".format(
            len(names)))

        for actuator in bus.actuators:
            start = bus.last_state(actuator.id).position
            lows[actuator.id] = start
            highs[actuator.id] = start

        if args.per_joint:
            # One joint at a time: move it to both ends, Enter advances. The
            # operator focuses on a single joint and sees its live angle, which
            # is what makes the extremes trustworthy -- no guessing which joint
            # a combined readout refers to.
            print("[teach] Per-joint. For each: move it to both ends, then "
                  "Enter for the next.")
            for name, actuator in zip(names, bus.actuators):
                low, high = teach_one(bus, name, actuator, args)
                lows[actuator.id] = low
                highs[actuator.id] = high
        else:
            print("[teach] Move every joint slowly to BOTH ends of its safe "
                  "range.")
            print("[teach] Ctrl-C when done (or wait {:.0f}s).\n".format(
                args.seconds))
            deadline = time.monotonic() + args.seconds
            next_print = 0.0
            while time.monotonic() < deadline:
                bus.poll(timeout=0.02)
                bus.check_fresh()
                for name, actuator in zip(names, bus.actuators):
                    state = bus.last_state(actuator.id)
                    if state.error:
                        raise RuntimeError("{} faulted: {}".format(
                            name, ERROR_NAMES.get(state.error, state.error)))
                    lows[actuator.id] = min(lows[actuator.id], state.position)
                    highs[actuator.id] = max(highs[actuator.id], state.position)

                now = time.monotonic()
                if now >= next_print:
                    parts = []
                    for name, actuator in zip(names, bus.actuators):
                        state = bus.last_state(actuator.id)
                        span = math.degrees(highs[actuator.id] - lows[actuator.id])
                        parts.append("{}: {:7.2f}deg  [{:7.2f} .. {:7.2f}] span {:6.2f}".format(
                            name, math.degrees(state.position),
                            math.degrees(lows[actuator.id]),
                            math.degrees(highs[actuator.id]), span))
                    print("  " + " | ".join(parts), end="\r", flush=True)
                    next_print = now + 0.1
    except KeyboardInterrupt:
        print("\n[teach] stopped by operator")
    except StaleFeedbackError as err:
        print("\n[teach] ABORT: {}".format(err), file=sys.stderr)
        return 1
    finally:
        bus.transport.close()

    print("\n" + "-" * 68)
    taught = []
    untaught = []
    for name, actuator in zip(names, bus.actuators):
        low_deg = math.degrees(lows[actuator.id])
        high_deg = math.degrees(highs[actuator.id])
        span = high_deg - low_deg
        if span < args.min_travel_deg:
            untaught.append((name, span))
            continue
        # Shrink inward: the extremes are where the joint was actually driven,
        # often the hard stop. Commanding exactly there is asking to stall.
        low_safe = low_deg + args.margin_deg
        high_safe = high_deg - args.margin_deg
        if low_safe >= high_safe:
            untaught.append((name, span))
            continue
        taught.append((name, low_safe, high_safe))
        print("[teach] {:<10s} moved {:7.2f} .. {:7.2f} deg (span {:6.2f})  "
              "-> limit [{:.2f}, {:.2f}] after {:.1f}deg margin".format(
                  name, low_deg, high_deg, span, low_safe, high_safe,
                  args.margin_deg))

    for name, span in untaught:
        print("[teach] {:<10s} moved only {:.2f} deg -- NOT taught, no limit "
              "written (it would lock the joint)".format(name, span),
              file=sys.stderr)

    if not taught:
        print("[teach] nothing was taught.", file=sys.stderr)
        return 1

    emit_config_snippet(taught, sys.stdout)

    if args.urdf:
        if untaught:
            # A URDF listing fewer joints than the config would silently
            # misalign the ros2_control joint order against the shm layout the
            # servicer fills -- i.e. commands landing on the wrong motor.
            print("\n[teach] refusing to write a URDF: {} of {} joints were not "
                  "taught ({}). A URDF missing a joint would misalign the "
                  "ros2_control joint order with the bus. Teach every joint, or "
                  "drop the untaught one from the config first.".format(
                      len(untaught), len(names),
                      ", ".join(n for n, _ in untaught)), file=sys.stderr)
            return 1
        if not args.urdf_effort or not args.urdf_velocity:
            print("\n[teach] --urdf needs --urdf-effort and --urdf-velocity. "
                  "They are real safety limits and this stack has no kt or "
                  "pole_pairs to derive them from, so it will not make them up.",
                  file=sys.stderr)
            return 2
        stamp = time.strftime("%Y-%m-%d %H:%M:%S")
        write_urdf(args.urdf, args.robot_name, args.shm_name, taught,
                   args.urdf_effort, args.urdf_velocity, stamp,
                   args.hardware_plugin)
        print("\n[teach] wrote {} -- limits are real, GEOMETRY IS A PLACEHOLDER "
              "(read its header)".format(args.urdf))

    if untaught:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
